"""Build the synthetic acceptance fixture package for Horizon 2.0.

Creates scripts/fixtures/spaced-repetition-practice.pptx: a small, legitimate
educational presentation about spaced repetition with speaker notes, matching
scripts/fixtures/spaced-repetition-demo.mp4 and .vtt. Everything here is
invented local test content, labelled as synthetic in the notes and README.

Usage:  python scripts/build-fixture-package.py
"""

from __future__ import annotations

from pathlib import Path

from pptx import Presentation
from pptx.util import Inches, Pt

FIXTURES = Path(__file__).resolve().parent / "fixtures"
OUTPUT = FIXTURES / "spaced-repetition-practice.pptx"

SLIDES = [
    (
        "Spaced Repetition",
        [
            "Memory decays on a predictable curve",
            "Review at expanding intervals to reset decay",
            "Typical first schedule: 1d, 3d, 1w, 2w, 1m",
        ],
        "Synthetic fixture content. Open by saying that the schedule exists to "
        "beat the forgetting curve, not to maximise total study minutes.",
    ),
    (
        "Retrieval Practice",
        [
            "Recall first, then check the answer",
            "Rereading produces fluency that fades",
            "Wrong answers restart the interval",
        ],
        "Synthetic fixture content. Emphasise that a failed recall is information: "
        "it moves the card back to the start of the schedule.",
    ),
    (
        "Interleaving and Card Design",
        [
            "Mix topics inside one session to improve transfer",
            "One idea per card keeps failures diagnosable",
            "Track intervals, not minutes spent studying",
        ],
        "Synthetic fixture content. Close by connecting interleaving to the "
        "decision step: choose the method before solving.",
    ),
]


def main() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    deck = Presentation()
    deck.core_properties.title = "Spaced Repetition Practice (synthetic fixture)"
    deck.core_properties.comments = (
        "Synthetic educational content generated by scripts/build-fixture-package.py "
        "for local acceptance testing of Horizon 2.0."
    )

    for title, bullets, notes in SLIDES:
        slide = deck.slides.add_slide(deck.slide_layouts[1])
        slide.shapes.title.text = title
        body = slide.placeholders[1].text_frame
        body.clear()
        for index, bullet in enumerate(bullets):
            paragraph = body.paragraphs[0] if index == 0 else body.add_paragraph()
            paragraph.text = bullet
            paragraph.level = 0
            paragraph.font.size = Pt(20)
        notes_frame = slide.notes_slide.notes_text_frame
        notes_frame.text = notes

    deck.save(OUTPUT)
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes, {len(SLIDES)} slides)")


if __name__ == "__main__":
    main()
